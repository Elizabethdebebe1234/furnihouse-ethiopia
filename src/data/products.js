// Get translated category
export function getLocalizedCategory(category, language = "en") {
  const translation = categoryTranslations[category.id]?.[language];

  return {
    ...category,
    name: translation?.name || category.name,
    description: translation?.description || category.description,
  };
}

// Get translated product
export function getLocalizedProduct(product, language = "en") {
  const translation = productTranslations[product.id]?.[language];

  return {
    ...product,
    name: translation?.[0] || product.name,
    description: translation?.[1] || product.description,
  };
}

// Get all translated products
export function getLocalizedProducts(language = "en") {
  return products.map((product) =>
    getLocalizedProduct(product, language)
  );
}

// Get all translated categories
export function getLocalizedCategories(language = "en") {
  return categories.map((category) =>
    getLocalizedCategory(category, language)
  );
}


export function formatETB(price) {
  return new Intl.NumberFormat("en-ET", {
    style: "currency",
    currency: "ETB",
    maximumFractionDigits: 0,
  }).format(price);
}
